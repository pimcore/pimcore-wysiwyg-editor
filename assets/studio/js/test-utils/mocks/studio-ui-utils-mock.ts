// Mock of the federated `@pimcore/studio-ui-bundle/utils` entry point, reduced to what the editor uses.
export const escapeHtml = (value: string): string => value
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;')

export const toCssDimension = (value?: string | number): string | undefined =>
  typeof value === 'number' ? `${value}px` : value
